const CLOUD_RUN_URL = "/run";

const EXAMPLE_1 = `1) Email from HR: Need your self-evaluation form completed by EOD tomorrow.
2) Slack from John: Hey, critical bug in the payment gateway, production is failing for 5% of users. Can you look NOW?
3) WhatsApp from Mom: Don't forget to buy tickets for the concert this weekend!
4) Jira Notification: Ticket #492 assigned to you (low priority UI tweak).
5) Email Newsletter: AI weekly digest - Check out the new Gemini 2.0 features.`;

const EXAMPLE_2 = `1) Note to self: Pay electricity bill today before 5 PM to avoid late fee.
2) Email from client: Requesting a status update on Project Alpha module. Needs response today.
3) Slack channel #general: Just sharing a funny meme. 
4) Calendar Alert: Doctor's appointment tomorrow at 10 AM.
5) Brainstorming idea: Maybe we should refactor the caching layer next week.`;

document.addEventListener('DOMContentLoaded', () => {
    const btnEx1 = document.getElementById('btn-example-1');
    const btnEx2 = document.getElementById('btn-example-2');
    const inputArea = document.getElementById('inbox-input');
    const btnAnalyze = document.getElementById('btn-analyze');
    
    const emptyState = document.getElementById('empty-state');
    const resultsContainer = document.getElementById('results-container');
    const itemsList = document.getElementById('items-list');

    const errorBanner = document.getElementById('error-banner');
    const errorTitle = document.getElementById('error-title');
    const errorMessage = document.getElementById('error-message');
    const btnErrorClose = document.getElementById('btn-error-close');

    btnErrorClose.addEventListener('click', () => errorBanner.classList.add('hidden'));

    btnEx1.addEventListener('click', () => inputArea.value = EXAMPLE_1);
    btnEx2.addEventListener('click', () => inputArea.value = EXAMPLE_2);

    btnAnalyze.addEventListener('click', async () => {
        const text = inputArea.value.trim();
        if (!text) {
            alert("Please paste some inbox text or use an example first.");
            return;
        }

        // Toggle UI states
        btnAnalyze.disabled = true;
        document.querySelector('.btn-text').textContent = "Agent is Thinking...";
        document.getElementById('loading-spinner').classList.remove('hidden');
        errorBanner.classList.add('hidden');
        
        try {
            // Generate a unique session ID for ADK tracking
            const sessionId = "demo-session-" + Date.now();
            const userId = "demo-user";
            const appName = "attention_triage_agent";

            // STEP 1: INITIALIZE SESSION
            // ADK's API requires an explicit session creation before running an agent.
            const sessionResponse = await fetch(`/apps/${appName}/users/${userId}/sessions/${sessionId}`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({})
            });

            if (!sessionResponse.ok) {
                const errText = await sessionResponse.text();
                throw new Error(`Failed to create ADK session: ${sessionResponse.status} - ${errText}`);
            }

            // STEP 2: RUN AGENT
            // Post to /run with the newly created session_id and the user message.
            // ADK 1.27.2 requires new_message to be a Content object with parts.
            const payload = {
                appName: appName,
                userId: userId,
                sessionId: sessionId,
                new_message: {
                    parts: [{ text: text }]
                }
            };

            const response = await fetch(CLOUD_RUN_URL, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify(payload)
            });

            if (!response.ok) {
                const errText = await response.text();
                throw new Error(`API Error: ${response.status} - ${errText}`);
            }

            const rawData = await response.json();
            console.log("Raw ADK Response:", rawData);

            // STEP 3: PARSE RESULTS
            // The ADK /run endpoint returns an array of events or a full state object.
            // We extract the final text generated by the Planner sub-agent.
            
            let jsonString = "";

            if (Array.isArray(rawData)) {
                // ADK 1.27.2 returns a list of Events. We search for the one from root agent.
                // An Event is an LlmResponse, so it has .content directly.
                const responseEvent = rawData.find(e => 
                    e.content && 
                    e.content.parts && 
                    e.content.parts.length > 0
                );
                
                if (responseEvent) {
                    jsonString = responseEvent.content.parts[0].text;
                } else {
                    // Fallback: look for ANY 'text' field in any event
                    const textEvent = rawData.find(e => e.text);
                    if (textEvent) jsonString = textEvent.text;
                }
            } else if (rawData.messages && rawData.messages.length > 0) {
                const lastMsg = rawData.messages[rawData.messages.length - 1];
                if (lastMsg.content && lastMsg.content.parts) {
                    jsonString = lastMsg.content.parts[0].text;
                }
            } else if (rawData.text) {
                jsonString = rawData.text;
            }

            if (!jsonString) {
                console.error("Unrecognized response format:", rawData);
                throw new Error("The agent matched your request but returned an empty response format. Try refreshing.");
            }

            // Clean markdown blocking if the LLM wrapped it in ```json ... ```
            jsonString = jsonString.replace(/```json/g, '').replace(/```/g, '').trim();

            const plan = JSON.parse(jsonString);
            
            if (plan.error) {
                showError("Agent Busy", plan.error);
                return;
            }
            
            renderResults(plan);

        } catch (error) {
            console.error("Error during analysis:", error);
            showError("Analysis Failed", error.message);
        } finally {
            btnAnalyze.disabled = false;
            document.querySelector('.btn-text').textContent = "Triage My Inbox";
            document.getElementById('loading-spinner').classList.add('hidden');
        }
    });

    function showError(title, message) {
        errorTitle.textContent = title;
        errorMessage.textContent = message;
        errorBanner.classList.remove('hidden');
        // Scroll to error if needed
        errorBanner.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }

    function renderResults(plan) {
        // Hide empty state, show results
        emptyState.classList.add('hidden');
        resultsContainer.classList.remove('hidden');

        // Render Summary & Metrics
        document.getElementById('plan-summary-text').textContent = plan.summary || "No summary provided.";
        document.getElementById('must-do-count').textContent = plan.must_do_today || 0;
        document.getElementById('defer-count').textContent = plan.can_defer || 0;

        // Render Items
        itemsList.innerHTML = '';
        if (plan.items && plan.items.length > 0) {
            plan.items.forEach((item, index) => {
                const urgencyClass = `tag-urgency-${(item.urgency || '').toLowerCase().replace(/\s+/g, '-')}`;
                
                let replyHtml = '';
                if (item.suggested_reply) {
                    replyHtml = `
                        <div class="reply-box">
                            <strong>Suggested Reply Draft:</strong>
                            <p>"${item.suggested_reply}"</p>
                        </div>
                    `;
                }

                const card = document.createElement('div');
                card.className = 'item-card';
                card.style.animationDelay = `${index * 0.1}s`;
                
                card.innerHTML = `
                    <div class="item-header">
                        <div class="item-raw">"${item.raw}"</div>
                    </div>
                    <div class="item-badges">
                        <span class="tag ${urgencyClass}">${item.urgency || 'N/A'}</span>
                        <span class="tag tag-neutral">${item.type || 'Unknown'}</span>
                        <span class="tag tag-neutral">${item.category || 'Other'}</span>
                        <span class="tag tag-neutral">⏱️ ${item.effort || '?'}</span>
                    </div>
                    <div class="item-details">
                        <div class="detail-row">
                            <span class="detail-label">Suggested Slot:</span>
                            <span class="detail-value">${item.suggested_slot || 'Anytime'}</span>
                        </div>
                    </div>
                    ${replyHtml}
                `;
                itemsList.appendChild(card);
            });
        }
    }
});
